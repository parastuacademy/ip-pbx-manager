"""Generates the Asterisk configuration fragments into the shared volume.

The panel is the single writer; Asterisk (other container / other role)
reads these files on every reload:

    /data/asterisk/pjsip_trunk.conf          transport + trunk + identify
    /data/asterisk/pjsip_endpoints.conf      one endpoint/auth/aor per extension
    /data/asterisk/globals.conf              INBOUND_DEST and other globals
    /data/asterisk/extensions_internal.conf  [internal] context (+ *98 voicemail)
    /data/asterisk/extensions_features.conf  ring groups + IVR contexts
    /data/asterisk/extensions_inbound.conf   business-hours / holiday / IVR flow
    /data/asterisk/voicemail.conf            voicemail boxes
"""
import json
import os

from . import db, jalali

DATA_DIR = os.environ.get("IPBX_DATA_DIR", "/data")
AST_DIR = os.path.join(DATA_DIR, "asterisk")
TRUNK_NAME = "pishgaman"
REC_DIR = os.path.join(DATA_DIR, "recordings")
SOUNDS_CUSTOM = os.path.join(AST_DIR, "sounds", "custom")
VM_SPOOL = os.path.join(DATA_DIR, "spool", "asterisk", "voicemail", "default")

HEADER = "; generated by ip-pbx-manager — do not edit by hand\n"

_ASTERISK_MONTHS = ("", "jan", "feb", "mar", "apr", "may", "jun",
                    "jul", "aug", "sep", "oct", "nov", "dec")


def _clean(value, default=""):
    """Strip characters that would break config syntax."""
    value = (value or "").replace('"', "").replace(";", "").strip()
    return value or default


def _codecs(settings):
    raw = _clean(settings.get("codecs"), "ulaw,alaw")
    allowed = [c.strip() for c in raw.split(",") if c.strip() in ("ulaw", "alaw", "g729", "gsm")]
    return ",".join(allowed) or "ulaw,alaw"


def _nat_lines(settings, indent=""):
    nat = _clean(settings.get("nat_public_ip"))
    lines = []
    if nat:
        lines.append(f"{indent}external_media_address = {nat}")
        lines.append(f"{indent}external_signaling_address = {nat}")
    return lines


# --------------------------------------------------------------------- pjsip
def _transport(settings):
    lines = [
        "[transport-udp]",
        "type = transport",
        "protocol = udp",
        "bind = 0.0.0.0:5060",
        "local_net = 10.0.0.0/8",
        "local_net = 172.16.0.0/12",
        "local_net = 192.168.0.0/16",
    ]
    lines += _nat_lines(settings)
    lines.append("")
    return lines


def write_trunk(settings, dst_dir=AST_DIR):
    mode = _clean(settings.get("trunk_mode"), "register")
    if mode not in ("register", "peer"):
        mode = "register"
    host = _clean(settings.get("trunk_host"))
    port = _clean(settings.get("trunk_port"), "5060")
    user = _clean(settings.get("trunk_user"))
    secret = _clean(settings.get("trunk_pass"))
    codecs = _codecs(settings)
    out = [HEADER, "; --- transport -------------------------------------------------"]
    out += _transport(settings)

    out += [
        f"; --- trunk: {TRUNK_NAME} ({mode}) ---------------------------------",
        f"[{TRUNK_NAME}]",
        "type = endpoint",
        "transport = transport-udp",
        "context = from-trunk",
        "disallow = all",
        f"allow = {codecs}",
        "dtmf_mode = rfc4733",
        "outbound_auth = pishgaman-auth",
        "aors = pishgaman",
    ]
    if mode == "register" and user:
        out += [f"from_user = {user}", f"from_domain = {host}"]
    out.append("")

    out += [
        f"[{TRUNK_NAME}]",
        "type = aor",
        f"contact = sip:{host}:{port}",
        "qualify_frequency = 60",
        "",
        "[pishgaman-auth]",
        "type = auth",
        "auth_type = userpass",
        f"username = {user}",
        f"password = {secret}",
        "",
        "[pishgaman-in]",
        "type = endpoint",
        "transport = transport-udp",
        "context = from-trunk",
        "disallow = all",
        f"allow = {codecs}",
        "dtmf_mode = rfc4733",
        "",
        "[pishgaman-identify]",
        "type = identify",
        "endpoint = pishgaman-in",
        f"match = {host}",
        "",
    ]

    if mode == "register" and user:
        out += [
            "[pishgaman-reg]",
            "type = registration",
            "outbound_auth = pishgaman-auth",
            f"server_uri = sip:{host}:{port}",
            f"client_uri = sip:{user}@{host}",
            "retry_interval = 60",
            "forbidden_retry_interval = 60",
            "expiration = 3600",
            "transport = transport-udp",
            "",
        ]
    path = os.path.join(dst_dir, "pjsip_trunk.conf")
    os.makedirs(dst_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    return path


def write_endpoints(exts, settings, dst_dir=AST_DIR):
    codecs = _codecs(settings)
    out = [HEADER, "; --- extensions ------------------------------------------------"]
    for e in exts:
        ext = _clean(e["ext"])
        name = _clean(e["display_name"], f"Ext {ext}")
        secret = _clean(e["secret"])
        if not ext or not secret:
            continue
        out += [
            f"[{ext}]",
            "type = endpoint",
            "transport = transport-udp",
            "context = internal",
            "disallow = all",
            f"allow = {codecs}",
            "dtmf_mode = rfc4733",
            f"auth = auth-{ext}",
            f"aors = {ext}",
            f'callerid = "{name}" <{ext}>',
            "",
            f"[auth-{ext}]",
            "type = auth",
            "auth_type = userpass",
            f"username = {ext}",
            f"password = {secret}",
            "",
            f"[{ext}]",
            "type = aor",
            "max_contacts = 3",
            "remove_existing = yes",
            "qualify_frequency = 60",
            "",
        ]
    path = os.path.join(dst_dir, "pjsip_endpoints.conf")
    os.makedirs(dst_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    return path


# ------------------------------------------------------------------ dialplan
def _dial_vm_lines(dest):
    """Dial an extension with voicemail fallback (AstDB vm/<ext>)."""
    return [
        f" same => n,Set(REC=${{DB(rec/{dest})}})",
        ' same => n,GotoIf($["${REC}"="1"]?rec:norec)',
        f" same => n(rec),MixMonitor({REC_DIR}/${{UNIQUEID}}.wav,b)",
        f" same => n(norec),Dial(PJSIP/{dest},45,t)",
        ' same => n,GotoIf($["${DIALSTATUS}"="ANSWER"]?hang)',
        f" same => n,Set(VM=${{DB(vm/{dest})}})",
        ' same => n,GotoIf($["${VM}"="1"]?vmx:hang)',
        f" same => n(vmx),VoiceMail({dest}@default,u)",
        " same => n(hang),Hangup()",
    ]


def _dest_jump(dest):
    """A Goto/VoiceMail line that hands the call to a destination."""
    kind, _, value = (dest or "").partition(":")
    if kind == "ext":
        return f"Goto(internal,{value},1)"
    if kind == "rg" and value:
        return f"Goto(rg-{value},s,1)"
    if kind == "ivr" and value:
        return f"Goto(ivr-{value},s,1)"
    if kind == "vm":
        return "VoiceMail(main@default,u)"
    return "Hangup()"


def _dest_command_lines(dest):
    """Plain dialplan commands (without prefix) that hand a call to a
    destination: ext:X (dial + vm fallback), rg:ID, ivr:ID, vm:main, ''."""
    kind, _, value = (dest or "").partition(":")
    if kind == "ext":
        return [
            f"Set(REC=${{DB(rec/${{CALLERID(num)}})}})",
            'GotoIf($["${REC}"="1"]?rec:norec)',
            f"MixMonitor({REC_DIR}/${{UNIQUEID}}.wav,b)",
            f"Dial(PJSIP/{value},45,t)",
            'GotoIf($["${DIALSTATUS}"="ANSWER"]?hang)',
            f"Set(VM=${{DB(vm/{value})}})",
            'GotoIf($["${VM}"="1"]?vmx:hang)',
            f"VoiceMail({value}@default,u)",
            "Hangup()",
        ]
    if kind == "rg" and value:
        return [f"Goto(rg-{value},s,1)"]
    if kind == "ivr" and value:
        return [f"Goto(ivr-{value},s,1)"]
    if kind == "vm":
        return ["VoiceMail(main@default,u)", "Hangup()"]
    return ["Hangup()"]


def _emit_fallback(out, dest, entry=None, label=None):
    """Append fallback lines. entry='exten => i' starts a new extension;
    entry=None continues the current one with ' same => n' (+ optional label)."""
    cmds = _dest_command_lines(dest)
    for idx, cmd in enumerate(cmds):
        if entry and idx == 0:
            out.append(f"{entry},1,{cmd}")
        elif idx == 0 and label:
            out.append(f" same => n({label}),{cmd}")
        else:
            out.append(f" same => n,{cmd}")


def _main_ivr(settings):
    """First IVR menu (or None)."""
    menus = db.list_ivr_menus()
    return menus[0] if menus else None


def write_dialplan(exts, settings, dst_dir=AST_DIR):
    os.makedirs(dst_dir, exist_ok=True)

    dest = _clean(settings.get("inbound_dest"))
    ivr = _main_ivr(settings)
    wh_enabled = settings.get("wh_enabled") == "1"
    closed_dest = _clean(settings.get("closed_dest")) or "vm:main"

    globals_path = os.path.join(dst_dir, "globals.conf")
    with open(globals_path, "w", encoding="utf-8") as fh:
        fh.write(HEADER)
        if dest:
            fh.write(f"INBOUND_DEST = {dest}\n")

    # ------------------------------------------------------------- internal
    internal = [HEADER, "[internal]"]
    for e in exts:
        ext = _clean(e["ext"])
        if not ext:
            continue
        # internal call: recorded when the CALLING extension has recording on,
        # voicemail when the CALLED extension has it enabled
        internal += [
            f"; --- extension {ext} ---",
            f"exten => {ext},1,NoOp(Call to {ext})",
            f" same => n,Set(REC=${{DB(rec/${{CALLERID(num)}})}})",
            ' same => n,GotoIf($["${REC}"="1"]?rec:norec)',
            f" same => n(rec),MixMonitor({REC_DIR}/${{UNIQUEID}}.wav,b)",
            f" same => n(norec),Dial(PJSIP/{ext},45,t)",
            ' same => n,GotoIf($["${DIALSTATUS}"="ANSWER"]?hang)',
            f" same => n,Set(VM=${{DB(vm/{ext})}})",
            ' same => n,GotoIf($["${VM}"="1"]?vmx:hang)',
            f" same => n(vmx),VoiceMail({ext}@default,u)",
            " same => n(hang),Hangup()",
            "",
        ]
    internal += [
        "; --- voicemail access from any phone ---",
        "exten => *98,1,VoiceMailMain(default)",
        " same => n,Hangup()",
        "",
    ]
    with open(os.path.join(dst_dir, "extensions_internal.conf"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(internal))

    # ------------------------------------------------------------- features
    features = [HEADER, "; ring groups (گروه زنگ) -------------------------------------"]
    for g in db.list_ring_groups():
        members = [m.strip() for m in (g["members"] or "").split(",") if m.strip()]
        members = [m for m in members if db.get_extension(m)]
        if not members:
            continue
        timeout = int(g["timeout"] or 20)
        features += [
            f"[rg-{g['id']}]",
            f"exten => s,1,NoOp(RingGroup: {g['name']})",
            f" same => n,Set(REC=${{DB(rec/${{CALLERID(num)}})}})",
            ' same => n,GotoIf($["${REC}"="1"]?rec:norec)',
            f" same => n(rec),MixMonitor({REC_DIR}/${{UNIQUEID}}.wav,b)",
            f" same => n(norec),Dial(PJSIP/{'&PJSIP/'.join(members)},{timeout},tT)",
            ' same => n,GotoIf($["${DIALSTATUS}"="ANSWER"]?hang)',
        ]
        _emit_fallback(features, g["fallback"] or "vm:main", label="fb")
        features.append("")
    features += ["; IVR menus (منوی صوتی) ---------------------------------------"]
    for m in db.list_ivr_menus():
        try:
            options = json.loads(m["options"] or "{}")
        except ValueError:
            options = {}
        prompt = _clean(m["prompt"])
        timeout = int(m["timeout"] or 6)
        features += [
            f"[ivr-{m['id']}]",
            f"exten => s,1,NoOp(IVR: {m['name']})",
            " same => n,Set(TIMEOUT(digit)=3)",
            f" same => n,Set(TIMEOUT(response)={timeout})",
        ]
        if prompt:
            features.append(f" same => n,Background({SOUNDS_CUSTOM}/{prompt})")
        features.append(" same => n,WaitExten()")
        features.append("")
        for digit, d in sorted(options.items()):
            if not digit.isdigit():
                continue
            features.append(f"exten => {digit},1,{_dest_jump(d)}")
            features.append(" same => n,Hangup()")
        features.append("")
        _emit_fallback(features, m["fallback"], entry="exten => i")
        features.append("")
        _emit_fallback(features, m["fallback"], entry="exten => t")
        features.append("")
    with open(os.path.join(dst_dir, "extensions_features.conf"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(features))

    # --------------------------------------------------------------- inbound
    inbound = [HEADER, "[from-trunk]"]
    if not dest and not ivr:
        inbound += ["; no inbound destination configured yet",
                    "exten => _X.,1,Hangup()", ""]
    else:
        inbound += [
            "exten => _X.,1,NoOp(inbound call ${CALLERID(num)})",
            " same => n,Set(CDR(userfield)=inbound)",
        ]
        if wh_enabled:
            for h in db.list_holidays():
                import re as _re
                m = _re.match(r"(\d{4})-(\d{2})-(\d{2})", h["gdate"] or "")
                if not m:
                    continue
                gm, gd = int(m.group(2)), int(m.group(3))
                inbound.append(
                    f" same => n,GotoIfTime(*,*,{gd},{_ASTERISK_MONTHS[gm]}?in-closed,s,1)"
                    f" ; {h['gdate']} {h['label']}")
            for day_idx in range(7):
                day = jalali.ASTERISK_DAYS[day_idx]
                o = _clean(settings.get(f"wh_open_{day_idx}"))
                c = _clean(settings.get(f"wh_close_{day_idx}"))
                if not o or not c or o == c:
                    continue
                inbound.append(
                    f" same => n,GotoIfTime({o}-{c},{day},*,*?in-open,s,1)")
            inbound.append(" same => n,Goto(in-closed,s,1)")
        else:
            inbound.append(" same => n,Goto(in-open,s,1)")
        inbound += [
            "",
            "[in-open]",
            "exten => s,1,NoOp(inside business hours)",
        ]
        if ivr:
            inbound.append(f" same => n,Goto(ivr-{ivr['id']},s,1)")
        elif dest:
            inbound += _dial_vm_lines(dest)
        else:
            inbound.append(" same => n,Hangup()")
        inbound += [
            "",
            "[in-closed]",
            "exten => s,1,NoOp(outside business hours)",
        ]
        _emit_fallback(inbound, closed_dest)
        inbound.append("")
    with open(os.path.join(dst_dir, "extensions_inbound.conf"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(inbound))
    return globals_path


def write_voicemail(exts, settings, dst_dir=AST_DIR):
    """voicemail.conf: main box + per-extension boxes (vm flag on)."""
    main_pass = _clean(settings.get("vm_main_pass"), "1234")
    smtp = _clean(settings.get("smtp_host"))
    out = [
        HEADER,
        "[general]",
        "format=wav",
        "attach=yes" if smtp else "attach=no",
    ]
    if smtp:
        out.append(f"serveremail={_clean(settings.get('smtp_from'), 'pbx@local')}")
    out += [
        "maxmsg=100",
        "maxsecs=180",
        "",
        "[default]",
        f"main => {main_pass},Main Voicemail,,",
    ]
    for e in exts:
        if not int(e.get("voicemail") or 0):
            continue
        ext = _clean(e["ext"])
        name = _clean(e["display_name"], f"Ext {ext}")
        secret = _clean(e["secret"])
        if ext and secret:
            out.append(f"{ext} => {secret},{name},,")
    path = os.path.join(dst_dir, "voicemail.conf")
    os.makedirs(dst_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    return path


# --------------------------------------------------------------------- apply
def apply_all(settings=None, exts=None, dst_dir=AST_DIR):
    """Regenerate every fragment from the database. Returns list of files."""
    settings = settings if settings is not None else db.all_settings()
    exts = exts if exts is not None else db.list_extensions()
    return [
        write_trunk(settings, dst_dir),
        write_endpoints(exts, settings, dst_dir),
        write_dialplan(exts, settings, dst_dir),
        write_voicemail(exts, settings, dst_dir),
    ]


def sync_record_flags(client, exts):
    """Mirror per-extension recording flags into Asterisk AstDB."""
    for e in exts:
        ext = str(e["ext"])
        if int(e.get("record") or 0):
            client.db_put_record(ext)
        else:
            client.db_del_record(ext)


def sync_vm_flags(client, exts):
    """Mirror per-extension voicemail flags into Asterisk AstDB."""
    for e in exts:
        ext = str(e["ext"])
        if int(e.get("voicemail") or 0):
            client.db_put_vm(ext)
        else:
            client.db_del_vm(ext)


def reload_asterisk(client):
    client.reload_all()
